package maintain

import (
	"bytes"
	"context"
	_ "embed"
	"errors"
	"fmt"
	"go/format"
	"os"
	"text/template"

	engine "github.com/MarkRosemaker/devtool-engine/maintain"
	"github.com/spf13/afero"
)

const (
	// webappMain is what a web app runs, generated, and webappApp what it
	// does, its own.
	webappMain = "main.go"
	webappApp  = "app.go"

	// webappModule is the library every web app is served by.
	webappModule = "github.com/MarkRosemaker/webapp"

	// goGenerated starts every Go file devtool writes.
	goGenerated = "// Code generated by MarkRosemaker/devtool. DO NOT EDIT."
)

var (
	//go:embed main.go.tmpl
	webappMainText string

	webappMainTmpl = template.Must(template.New(webappMain).Parse(webappMainText))
)

// webappStarter is app.go as it is first written, for the app to fill in.
const webappStarter = `package main

import (
	"context"
	"net/http"
)

// setup opens what the app needs and registers its API on mux, under /api.
// It returns the handler to serve, mux itself or one wrapping it, and a
// function closing what it opened, run once the server has shut down.
func setup(_ context.Context, mux *http.ServeMux) (http.Handler, func(), error) {
	return mux, func() {}, nil
}
`

// webappData is what [webappMainTmpl] is executed against.
type webappData struct {
	Name, Description string
	Webapp

	// OpenAPI and AsyncAPI are the specs the app has under api/, and
	// Interactions and Sessions what each is enriched from.
	OpenAPI, Interactions, AsyncAPI, Sessions bool
}

// WebappTask writes the main.go of a web app whose devtool.json has a webapp
// section: the go:generate lines for the specs under api/, the embedded
// frontend/, and a call to webapp.Main, which serves it. The first time, it
// also writes app.go, where the app's setup starts; from then on app.go is
// the app's own.
//
// A main.go of the app's own is refused rather than overwritten: what it does
// moves into setup first.
func WebappTask(repo engine.Repo) engine.Task {
	return engine.Task{
		Name:  "webapp",
		Short: "webapp",
		Run: func(context.Context) error {
			return writeWebapp(repo.Fs())
		},
	}
}

func writeWebapp(fs afero.Fs) error {
	def, _, err := LoadDefinition(fs)
	if err != nil {
		return err
	}

	if def.Webapp == nil {
		return nil
	}

	if err := checkWebapp(fs, def); err != nil {
		return fmt.Errorf("%s: %w", DefinitionPath, err)
	}

	existing, err := afero.ReadFile(fs, webappMain)

	first := errors.Is(err, os.ErrNotExist)
	if err != nil && !first {
		return err
	}

	if !first && !bytes.HasPrefix(existing, []byte(goGenerated)) {
		return fmt.Errorf("%s is the app's own: move what it does into setup, in %s, and delete it, "+
			"for devtool to write it", webappMain, webappApp)
	}

	data := webappData{Name: def.Name, Description: def.Description, Webapp: *def.Webapp}

	for _, spec := range []struct {
		file string
		has  *bool
	}{
		{"api/openapi.json", &data.OpenAPI},
		{interactionsPath, &data.Interactions},
		{"api/asyncapi.json", &data.AsyncAPI},
		{"api/sessions.json", &data.Sessions},
	} {
		if *spec.has, err = afero.Exists(fs, spec.file); err != nil {
			return err
		}
	}

	var buf bytes.Buffer
	if err := webappMainTmpl.Execute(&buf, data); err != nil {
		return fmt.Errorf("%s: %w", webappMain, err)
	}

	src, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("%s: %w", webappMain, err)
	}

	if err := afero.WriteFile(fs, webappMain, src, 0o644); err != nil {
		return err
	}

	if !first {
		return nil
	}

	if ok, err := afero.Exists(fs, webappApp); err != nil || ok {
		return err
	}

	return afero.WriteFile(fs, webappApp, []byte(webappStarter), 0o644)
}

// checkWebapp refuses what main.go could not be written or built from, saying
// what to add.
func checkWebapp(fs afero.Fs, def Definition) error {
	switch {
	case def.Kind != KindWebapp:
		return fmt.Errorf("a webapp section needs \"kind\": %q", KindWebapp)
	case def.Name == "":
		return errors.New(`a web app needs a "name", which its pages and the installed app are called`)
	case def.Webapp.Port <= 0 || def.Webapp.Port > 65535:
		return fmt.Errorf(`webapp: "port" %d is no port to listen on locally`, def.Webapp.Port)
	}

	if ok, err := afero.DirExists(fs, "frontend"); err != nil {
		return err
	} else if !ok {
		return errors.New("a web app serves frontend/, which is missing: export the design into it")
	}

	if ok, err := requires(fs, webappModule); err != nil {
		return err
	} else if !ok {
		return fmt.Errorf("go.mod does not require %s, which serves the app; go get it", webappModule)
	}

	return nil
}
