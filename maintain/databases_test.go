// TestADatabaseNeedsSQLC: sqlc is pinned and installed only where a
// database is declared.
func TestADatabaseNeedsSQLC(t *testing.T) {
	has := func(def Definition) bool {
		for _, tool := range toolsFor(def) {
			if tool.Name == sqlcTool.Name {
				return true
			}
		}

		return false
	}

	if has(Definition{}) {
		t.Error("sqlc is a tool of a repository without databases")
	}

	if !has(Definition{Resources: Resources{Databases: []Database{{Name: "user"}}}}) {
		t.Error("sqlc is not a tool of a repository with a database")
	}
}

