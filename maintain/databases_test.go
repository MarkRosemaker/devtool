// databaseRepo is a repository declaring one database, user, with its
// initial migration and a query file.
func databaseRepo(t *testing.T) *fakeRepo {
	t.Helper()

	repo := &fakeRepo{}
	fs := repo.Fs()

	writeFile(t, fs, "go.mod", "module example.com/app\n\ngo 1.27\n\nrequire modernc.org/sqlite v1.0.0\n")
	writeFile(t, fs, DefinitionPath, `{"resources": {"databases": [{"name": "user"}]}}`+"\n")
	writeFile(t, fs, "databases/user/migrations/001_initial.up.sql",
		"CREATE TABLE users (id INTEGER PRIMARY KEY, name TEXT NOT NULL);\n")
	writeFile(t, fs, "databases/user/queries/users.sql",
		"-- name: GetUser :one\nSELECT * FROM users WHERE id = ?;\n")

	return repo
}

func runDatabases(t *testing.T, repo *fakeRepo) error {
	t.Helper()

	return DatabasesTask(repo).Run(t.Context())
}

func TestDatabasesWritesTheFiles(t *testing.T) {
	repo := databaseRepo(t)
	if err := runDatabases(t, repo); err != nil {
		t.Fatal(err)
	}

	fs := repo.Fs()

	for file, wants := range map[string][]string{
		"databases/user/sqlc.yaml": {
			"# generated by MarkRosemaker/devtool", "schema: migrations", "queries: queries",
			"package: user", "out: .",
		},
		"databases/user/generate.go": {"package user\n", "//go:generate sqlc generate\n"},
		"databases/user/migrate.go":  {"package user\n", "//go:embed migrations/*.up.sql", "func Migrate("},
		"databases/user/open.go": {
			"package user\n", `_ "modernc.org/sqlite"`, `sql.Open("sqlite", "file:"+path+"?"+options)`, "_txlock=immediate",
			`filepath.Join(home, ".gorepo", "user.db")`, "type DB struct",
			"func Open(ctx context.Context, path string) (*DB, error)",
			"func (d *DB) Close() error", "func (d *DB) WithTx(",
		},
	} {
		got := readFile(t, fs, file)

		for _, want := range wants {
			if !strings.Contains(got, want) {
				t.Errorf("%s lacks %q:\n%s", file, want, got)
			}
		}
	}
}

// TestDatabasesIsIdempotent: a second run writes the same bytes, or every
// maintained run would commit.
func TestDatabasesIsIdempotent(t *testing.T) {
	repo := databaseRepo(t)
	if err := runDatabases(t, repo); err != nil {
		t.Fatal(err)
	}

	first := snapshot(t, repo.Fs())

	if err := runDatabases(t, repo); err != nil {
		t.Fatal(err)
	}

	for f, b := range snapshot(t, repo.Fs()) {
		if first[f] != b {
			t.Errorf("%s changed on a second run", f)
		}
	}
}

// TestDatabasesRemovesOnlyOrphans: sqlc never deletes the code of a query
// file that has gone, so devtool does — and nothing else, since it may run
// where sqlc does not follow to write the rest again.
func TestDatabasesRemovesOnlyOrphans(t *testing.T) {
	repo := databaseRepo(t)
	fs := repo.Fs()

	const sqlc = "// Code generated by sqlc. DO NOT EDIT.\n// versions:\n//   sqlc v1.31.1\n"

	writeFile(t, fs, "databases/user/users.sql.go", sqlc+"// source: users.sql\n\npackage user\n")
	writeFile(t, fs, "databases/user/names.sql.go", sqlc+"// source: names.sql\n\npackage user\n")
	writeFile(t, fs, "databases/user/db.go", sqlc+"\npackage user\n")
	writeFile(t, fs, "databases/user/mine.sql.go", "// source: gone.sql\n\npackage user\n")

	if err := runDatabases(t, repo); err != nil {
		t.Fatal(err)
	}

	for file, kept := range map[string]bool{
		"databases/user/users.sql.go": true,  // its query file is there
		"databases/user/names.sql.go": false, // names.sql has gone
		"databases/user/db.go":        true,  // generated from no one file
		"databases/user/mine.sql.go":  true,  // not sqlc's
	} {
		if _, err := fs.Stat(file); (err == nil) != kept {
			t.Errorf("%s: kept = %v, want %v", file, err == nil, kept)
		}
	}
}

func TestDatabasesRefuses(t *testing.T) {
	for _, tc := range []struct {
		name, file, content, want string
		remove                    string
	}{
		{
			name: "a name that cannot be a package",
			file: DefinitionPath, content: `{"resources": {"databases": [{"name": "User-DB"}]}}`,
			want: "names the package",
		},
		{
			name: "a name with a digit",
			file: DefinitionPath, content: `{"resources": {"databases": [{"name": "user2"}]}}`,
			want: "letters only",
		},
		{
			name:   "no initial migration",
			remove: "databases/user/migrations/001_initial.up.sql",
			want:   "001_initial.up.sql",
		},
		{
			name: "no driver to open it with",
			file: "go.mod", content: "module example.com/app\n\ngo 1.27\n",
			want: "modernc.org/sqlite",
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			repo := databaseRepo(t)

			if tc.file != "" {
				writeFile(t, repo.Fs(), tc.file, tc.content)
			}

			if tc.remove != "" {
				if err := repo.Fs().Remove(tc.remove); err != nil {
					t.Fatal(err)
				}
			}

			if err := runDatabases(t, repo); err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Errorf("want a refusal mentioning %q, got %v", tc.want, err)
			}
		})
	}
}

func TestSQLiteDriverFollowsGoMod(t *testing.T) {
	fs := afero.NewMemMapFs()
	writeFile(t, fs, "go.mod",
		"module example.com/app\n\ngo 1.27\n\nrequire github.com/ncruces/go-sqlite3 v0.35.5\n")

	driver, imports, err := sqliteDriver(fs)
	if err != nil {
		t.Fatal(err)
	}

	if driver != "sqlite3" || len(imports) != 1 || imports[0] != "github.com/ncruces/go-sqlite3/driver" {
		t.Errorf("ncruces gave %q %v", driver, imports)
	}
}

// TestADatabaseNeedsSQLC: sqlc is pinned and installed only where a
// database is declared.
func TestADatabaseNeedsSQLC(t *testing.T) {
	has := func(def Definition) bool {
		for _, tool := range toolsFor(def) {
			if tool.Name == sqlcTool.Name {
				return true
			}
		}

		return false
	}

	if has(Definition{}) {
		t.Error("sqlc is a tool of a repository without databases")
	}

	if !has(Definition{Resources: Resources{Databases: []Database{{Name: "user"}}}}) {
		t.Error("sqlc is not a tool of a repository with a database")
	}
}

