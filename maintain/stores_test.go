// storeRepo is a repository declaring stores, with go.mod requiring the S3
// client where client is set.
func storeRepo(t *testing.T, stores string, client bool) *fakeRepo {
	t.Helper()

	repo := &fakeRepo{}
	mod := "module example.com/app\n\ngo 1.27\n"

	if client {
		mod += "\nrequire (\n\tgithub.com/aws/aws-sdk-go-v2/credentials v1.0.0\n\tgithub.com/aws/aws-sdk-go-v2/service/s3 v1.0.0\n)\n"
	}

	writeFile(t, repo.Fs(), "go.mod", mod)
	writeFile(t, repo.Fs(), DefinitionPath, `{"resources": {"stores": `+stores+`}}`+"\n")

	return repo
}

// A store is a package of its own: the bucket, reached from the environment,
// and a test's bucket beside it.
func TestStoresWritesTheFiles(t *testing.T) {
	repo := storeRepo(t, `[{"name": "pictures", "bucket": "assets"}]`, true)
	if err := StoresTask(repo).Run(t.Context()); err != nil {
		t.Fatal(err)
	}

	for file, wants := range map[string][]string{
		"stores/pictures/store.go": {
			"// Code generated by MarkRosemaker/devtool. DO NOT EDIT.", "package pictures\n",
			`const Bucket = "assets"`, `EnvEndpoint        = "GOREPO_STORAGE_ENDPOINT"`,
			`EnvSecretAccessKey = "GOREPO_STORAGE_SECRET_ACCESS_KEY"`,
			"func Open(ctx context.Context) (*Store, error)", "func Reach(ctx context.Context, client *s3.Client) (*Store, error)",
			"func (s *Store) Has(", "func (s *Store) Put(", "func (s *Store) Get(", "func (s *Store) Read(",
		},
		"stores/pictures/picturestest/picturestest.go": {
			"package picturestest\n", `"example.com/app/stores/pictures"`,
			"func Open(t testing.TB) (*pictures.Store, *Bucket)", "pictures.NewClient(srv.URL,",
		},
	} {
		got := readFile(t, repo.Fs(), file)

		for _, want := range wants {
			if !strings.Contains(got, want) {
				t.Errorf("%s lacks %q:\n%s", file, want, got)
			}
		}
	}

	if len(repo.commands) != 0 {
		t.Errorf("ran %q with the client already required", repo.commands)
	}
}

// Without the S3 client in go.mod, the task adds it and tidies, vendoring
// where the repository vendors.
func TestStoresAddsTheClient(t *testing.T) {
	repo := storeRepo(t, `[{"name": "files"}]`, false)
	writeFile(t, repo.Fs(), "vendor/modules.txt", "")

	if err := StoresTask(repo).Run(t.Context()); err != nil {
		t.Fatal(err)
	}

	want := []string{
		"go get github.com/aws/aws-sdk-go-v2/service/s3",
		"go get github.com/aws/aws-sdk-go-v2/credentials",
		"go mod tidy", "go mod vendor",
	}
	if !slices.Equal(repo.commands, want) {
		t.Errorf("ran %q\nwant %q", repo.commands, want)
	}

	if got := readFile(t, repo.Fs(), "stores/files/store.go"); !strings.Contains(got, `const Bucket = "files"`) {
		t.Errorf("a store without a bucket keeps its files in one named after it:\n%s", got)
	}
}

func TestStoresRefuses(t *testing.T) {
	for _, tc := range []struct{ stores, want string }{
		{`[{"name": "My-Files"}]`, "lower-case letters only"},
		{`[{"name": "files", "bucket": "UPPER"}]`, "no name S3 allows"},
		{`[{"name": "files", "bucket": "ab"}]`, "no name S3 allows"},
	} {
		err := StoresTask(storeRepo(t, tc.stores, true)).Run(t.Context())
		if err == nil || !strings.Contains(err.Error(), tc.want) {
			t.Errorf("%s: err = %v, want it to say %q", tc.stores, err, tc.want)
		}
	}
}

// The variables are named after the repository, and the store where there is
// more than one, as a database's URL is.
func TestEnvStorage(t *testing.T) {
	if got := envStorage("atelier", "pictures", true); got != "ATELIER_STORAGE" {
		t.Errorf("one store: %q", got)
	}

	if got := envStorage("private-file-vault", "pictures", false); got != "PRIVATE_FILE_VAULT_PICTURES_STORAGE" {
		t.Errorf("one of several: %q", got)
	}
}

func TestStoreIsGo(t *testing.T) {
	data := struct{ Package, Module, Bucket, Env string }{"pictures", "example.com/app", "assets", "APP_STORAGE"}

	for name, tmpl := range map[string]*template.Template{"store.go": storeTmpl, "storetest.go": storetestTmpl} {
		b, err := render(tmpl, data)
		if err != nil {
			t.Fatal(err)
		}

		formatted, err := format.Source(b)
		if err != nil {
			t.Fatalf("%s: not Go: %v\n%s", name, err, b)
		}

		if !bytes.Equal(formatted, b) {
			t.Errorf("%s: not gofmt'd:\n%s", name, b)
		}
	}
}
