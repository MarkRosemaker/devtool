// TestReadmeTemplateWhitespace holds the template to generating the blank
// lines itself, correctly, rather than being tidied up afterwards: whatever
// combination of sections renders, no run of blank lines and no leading one.
func TestReadmeTemplateWhitespace(t *testing.T) {
	for _, tc := range readmeCases {
		t.Run(tc.name, func(t *testing.T) {
			buf := &bytes.Buffer{}
			if err := readmeTmpl.Execute(buf, tc.data); err != nil {
				t.Fatal(err)
			}

			raw := buf.String()

			if strings.Contains(raw, "\n\n\n") {
				t.Errorf("raw template output has more than one blank line in a row:\n%q", raw)
			}

			if strings.HasPrefix(raw, "\n") {
				t.Errorf("raw template output starts with a blank line: %q", raw)
			}

			// The stamp is an HTML comment: invisible once rendered, so
			// whatever follows it needs no blank line of its own.
			if strings.Contains(raw, wantStamp+"\n\n") {
				t.Errorf("a blank line follows the stamp: %q", raw)
			}
		})
	}
}

// TestReadmeGolden renders each case against a golden file, so a change to
// the template shows up as a reviewable diff rather than as prose in a test
// assertion. Run "go test ./maintain -update" to rewrite them.
func TestReadmeGolden(t *testing.T) {
	for _, tc := range readmeCases {
		t.Run(tc.name, func(t *testing.T) {
			got, err := renderReadme(tc.data)
			if err != nil {
				t.Fatal(err)
			}

			golden := filepath.Join("testdata", "README."+tc.name+".golden")

			if *update {
				if err := os.WriteFile(golden, got, 0o644); err != nil {
					t.Fatal(err)
				}

				return
			}

			want, err := os.ReadFile(golden)
			if err != nil {
				t.Fatalf("%v (run: go test ./maintain -update)", err)
			}

			if !bytes.Equal(got, want) {
				t.Errorf("%s does not match:\n--- got ---\n%s\n--- want ---\n%s", golden, got, want)
			}
		})
	}
}

